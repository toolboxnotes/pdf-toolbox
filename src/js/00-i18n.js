const LANGS = [['en', 'English'], ['ko', '한국어'], ['zh', '中文']];
function detectLang() {
  try { const s = localStorage.getItem('pdftool.lang'); if (s) return s; } catch {}
  const q = new URLSearchParams(location.search).get('lang');
  if (q) return q;
  const n = (navigator.language || 'en').toLowerCase();
  return n.startsWith('ko') ? 'ko' : n.startsWith('zh') ? 'zh' : 'en';
}
const LANG = LANGS.some(l => l[0] === detectLang()) ? detectLang() : 'en';
document.documentElement.lang = { en: 'en', ko: 'ko', zh: 'zh-CN' }[LANG];
// T(original Chinese text, ...args): returns the text in the current language; {0}{1}… are replaced by the args in order
function T(key, ...args) {
  const e = I18N[key];
  let s = LANG === 'zh' || !e ? key : e[LANG === 'en' ? 0 : 1];
  if (args.length) s = s.replace(/\{(\d+)\}/g, (m, i) => (args[i] !== undefined ? args[i] : m));
  return s;
}
function setLang(l) {
  try { localStorage.setItem('pdftool.lang', l); } catch {}
  const u = new URL(location.href);
  u.searchParams.set('lang', l);
  location.href = u.href;
}
